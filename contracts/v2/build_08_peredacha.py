"""
Документ 08: Приложение № 7 — Регламент передачи материалов при расторжении.

Защита Исполнителя:
- передача только после полной оплаты и подписания акта сверки;
- удержание материалов в обеспечение задолженности (ст. 359 ГК РФ);
- чёткий перечень — Исполнитель не передаёт собственные методики, скрипты,
  плейбуки сверх того, что согласовано;
- сроки и формат передачи.
"""
from _shared import (
    new_document,
    add_title,
    add_subtitle,
    add_h1,
    add_h2,
    add_clause,
    add_paragraph,
    add_bullet,
    add_table,
    add_signature_block,
    save,
)


def build():
    doc = new_document()

    add_title(
        doc,
        "Приложение № 7 к Договору № __/____\n"
        "возмездного оказания услуг от «___» __________ 20__ г.",
    )
    add_subtitle(doc, "Регламент передачи материалов при расторжении Договора")

    # ------------------------------------------------------------------
    add_h1(doc, "1. Назначение")
    add_paragraph(
        doc,
        "Настоящее Приложение устанавливает порядок и состав материалов, передаваемых "
        "Исполнителем Заказчику при прекращении Договора по любому основанию, а также порядок "
        "взаимодействия Сторон в переходный период.",
    )

    # ------------------------------------------------------------------
    add_h1(doc, "2. Условия передачи")
    add_clause(
        doc, "2.1",
        "Материалы передаются Заказчику **только при выполнении одновременно всех** следующих "
        "условий:",
    )
    add_bullet(doc, "Заказчик полностью погасил задолженность перед Исполнителем (включая последний оплачиваемый месяц обслуживания, неустойки, штрафные санкции, расходы по доп. услугам);")
    add_bullet(doc, "Сторонами подписан акт сверки взаимных расчётов с нулевым сальдо в пользу Заказчика либо подтверждено отсутствие задолженности;")
    add_bullet(doc, "Заказчик письменно подтвердил готовность принять материалы и предоставил защищённый канал получения (S3-бакет, шифрованный архив с парольной защитой, передача на физический носитель).")
    add_clause(
        doc, "2.2",
        "**Право удержания материалов.** В случае наличия задолженности Исполнитель вправе "
        "удерживать материалы до её полного погашения в соответствии с п. 1 ст. 359 ГК РФ. "
        "Удержание не является основанием для требования возмещения убытков со стороны "
        "Заказчика.",
    )
    add_clause(
        doc, "2.3",
        "Передача материалов осуществляется в течение **15 (пятнадцати) рабочих дней** с даты "
        "выполнения условий п. 2.1.",
    )

    # ------------------------------------------------------------------
    add_h1(doc, "3. Состав передаваемых материалов")
    add_h2(doc, "3.1. Безусловно передаются Заказчику:")
    add_bullet(doc, "конфигурационные файлы серверов и сервисов Заказчика из системы контроля версий (Git-репозиторий или экспорт в архиве);")
    add_bullet(doc, "ключи доступа, пароли и иные учётные данные, относящиеся к инфраструктуре Заказчика (через защищённый канал);")
    add_bullet(doc, "отчёты за период обслуживания (еженедельные / ежемесячные — в зависимости от Тарифа);")
    add_bullet(doc, "журналы доступа специалистов Исполнителя к инфраструктуре Заказчика за последние 12 месяцев (экспорт из Loki / Wazuh, при наличии);")
    add_bullet(doc, "инструкции по подключению к системам мониторинга, бэкапов, SIEM (если они размещены на стороне Исполнителя — инструкции по экспорту/восстановлению на стороне Заказчика);")
    add_bullet(doc, "акт о принятых мерах защиты ПДн (для Тарифов Silver / Gold) — однократно, в редакции на дату расторжения;")
    add_bullet(doc, "схема сети и схема резервного копирования в виде, актуальном на дату расторжения.")

    add_h2(doc, "3.2. Передаётся при наличии прямой связи с инфраструктурой Заказчика:")
    add_bullet(doc, "Ansible-роли и Puppet-манифесты, разработанные исключительно для инфраструктуры Заказчика;")
    add_bullet(doc, "Grafana-дашборды, развёрнутые в рамках обслуживания (JSON-экспорт);")
    add_bullet(doc, "кастомные правила Wazuh (для Gold), относящиеся к инфраструктуре Заказчика;")
    add_bullet(doc, "пост-мортем-отчёты по инцидентам в инфраструктуре Заказчика.")

    add_h2(doc, "3.3. НЕ передаётся Заказчику")
    add_paragraph(doc, "Не подлежит передаче следующее (является результатом интеллектуальной деятельности Исполнителя и сохраняется за ним):")
    add_bullet(doc, "общие методики, регламенты, runbooks, не разработанные специально для инфраструктуры Заказчика;")
    add_bullet(doc, "Ansible-роли / Puppet-манифесты общего назначения, используемые Исполнителем у множества клиентов;")
    add_bullet(doc, "правила мониторинга и SIEM общего характера (Prometheus rules, Alertmanager rules, Wazuh rules), не привязанные к конкретной инфраструктуре Заказчика;")
    add_bullet(doc, "внутренние документы Исполнителя (политики, инструкции, обучающие материалы для сотрудников Исполнителя);")
    add_bullet(doc, "коммерческие данные Исполнителя (прайсы, контакты партнёров, договоры с поставщиками);")
    add_bullet(doc, "программные средства Исполнителя, используемые для оказания Услуг (системы мониторинга, тикетинг, инструменты разработки), за исключением экспорта данных, относящихся к инфраструктуре Заказчика.")

    # ------------------------------------------------------------------
    add_h1(doc, "4. Порядок передачи")
    add_clause(
        doc, "4.1",
        "Передача материалов оформляется **Актом приёма-передачи** с перечнем переданных файлов / "
        "контейнеров, контрольными суммами и датами. Акт подписывается обеими Сторонами.",
    )
    add_clause(
        doc, "4.2",
        "Учётные данные и пароли передаются **только через защищённый канал** (1Password share, "
        "Bitwarden Send, шифрованный архив с паролем по отдельному каналу). Передача в "
        "незащищённом виде (электронная почта, мессенджер без шифрования) **не допускается**.",
    )
    add_clause(
        doc, "4.3",
        "После передачи и подписания Акта приёма-передачи Исполнитель в течение **30 (тридцати) "
        "календарных дней**:",
    )
    add_bullet(doc, "удаляет все учётные данные и пароли Заказчика из своих систем управления секретами;")
    add_bullet(doc, "удаляет данные мониторинга Заказчика (Prometheus, Loki, Wazuh), за исключением сведений, требующих обязательного хранения по законодательству;")
    add_bullet(doc, "уничтожает резервные копии Заказчика в облачном хранилище в порядке, согласованном Сторонами в Акте приёма-передачи (по умолчанию — немедленное уничтожение после успешной выгрузки Заказчику).")

    add_clause(
        doc, "4.4",
        "**Сведения, обязательные к хранению по законодательству РФ** (например, финансовая "
        "отчётность — 5 лет в силу 402-ФЗ; данные о расчётах через приложение «Мой налог»), "
        "сохраняются Исполнителем в течение нормативных сроков с обеспечением их "
        "конфиденциальности.",
    )

    # ------------------------------------------------------------------
    add_h1(doc, "5. Переходный период")
    add_clause(
        doc, "5.1",
        "В период между уведомлением о расторжении и фактической передачей материалов "
        "Исполнитель **продолжает оказывать Услуги в стандартном объёме** при условии "
        "своевременной оплаты Заказчиком.",
    )
    add_clause(
        doc, "5.2",
        "**Дополнительные услуги по поддержке миграции к новому подрядчику** не входят в "
        "Тариф и оказываются по прайсу Приложения № 1 либо по отдельному согласованию. "
        "В частности:",
    )
    add_bullet(doc, "проведение сопровождающих сессий с новым подрядчиком Заказчика — 3 000 ₽ за час;")
    add_bullet(doc, "развёрнутая техническая консультация для новой команды — по почасовой ставке Тарифа;")
    add_bullet(doc, "сопровождение миграции мониторинга / бэкапов / SIEM на инфраструктуру нового подрядчика — по смете.")

    # ------------------------------------------------------------------
    add_h1(doc, "6. Ответственность за неисполнение Регламента")
    add_clause(
        doc, "6.1",
        "При неисполнении Заказчиком п. 2.1 (наличии непогашенной задолженности) Исполнитель "
        "не несёт ответственности за непередачу материалов до даты погашения долга. "
        "Указанное обстоятельство не является основанием для требований Заказчика о возмещении "
        "убытков, упущенной выгоды и неустоек.",
    )
    add_clause(
        doc, "6.2",
        "При неисполнении Заказчиком п. 4.3 (готовность принять и канал получения) Исполнитель "
        "вправе уничтожить материалы по истечении **90 (девяноста) календарных дней** с даты "
        "уведомления Заказчика о готовности к передаче, направив повторное предупреждение за "
        "10 дней.",
    )

    # ------------------------------------------------------------------
    add_h1(doc, "7. Подписи Сторон")
    add_signature_block(
        doc,
        [
            ("Исполнитель", ["__ФИО__, плательщик НПД", "ИНН: __________________"]),
            ("Заказчик", ["__Полное наименование__", "ИНН: __________________"]),
        ],
    )

    path = save(doc, "08_prilozhenie_7_peredacha.docx")
    print(f"OK: {path}")


if __name__ == "__main__":
    build()
