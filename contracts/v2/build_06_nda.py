"""
Документ 06: Приложение № 5 — Соглашение о конфиденциальности (NDA).

Двустороннее, с упором на защиту Исполнителя:
- Конфиденциальной является и информация Заказчика, и информация Исполнителя
  (включая внутренние процессы, прайсы, методики).
- Срок 3 года после прекращения Договора.
- Чёткая ответственность, штраф за нарушение.
- Применимо законодательство РФ + ст. 1465 ГК РФ «секрет производства» + 98-ФЗ
  «О коммерческой тайне».
"""
from _shared import (
    new_document,
    add_title,
    add_subtitle,
    add_h1,
    add_h2,
    add_clause,
    add_paragraph,
    add_bullet,
    add_note,
    add_table,
    add_signature_block,
    save,
)


def build():
    doc = new_document()

    add_title(
        doc,
        "Приложение № 5 к Договору № __/____\n"
        "возмездного оказания услуг от «___» __________ 20__ г.",
    )
    add_subtitle(doc, "Соглашение о конфиденциальности (NDA)")

    # ------------------------------------------------------------------
    add_h1(doc, "1. Предмет Соглашения")
    add_paragraph(
        doc,
        "Настоящее Соглашение регулирует порядок обращения Сторон с конфиденциальной информацией, "
        "ставшей известной им в ходе заключения и исполнения Договора.",
    )
    add_paragraph(
        doc,
        "Стороны взаимно признают друг друга «**Раскрывающей Стороной**» (в отношении сведений, "
        "которые она передаёт) и «**Получающей Стороной**» (в отношении сведений, которые "
        "получает). Соглашение является **двусторонним**.",
    )

    # ------------------------------------------------------------------
    add_h1(doc, "2. Конфиденциальная информация")
    add_paragraph(
        doc,
        "Под конфиденциальной информацией в настоящем Соглашении понимаются любые сведения, "
        "имеющие действительную или потенциальную коммерческую ценность в силу неизвестности их "
        "третьим лицам, переданные одной Стороной другой Стороне в письменной, устной, "
        "электронной или иной форме в связи с Договором, в том числе:",
    )

    add_h2(doc, "2.1. Со стороны Заказчика — Исполнителю")
    add_bullet(doc, "конфигурация инфраструктуры, схемы сети, IP-адреса, имена хостов, состав ПО;")
    add_bullet(doc, "учётные данные, ключи доступа, сертификаты, пароли;")
    add_bullet(doc, "данные о клиентах, контрагентах, сотрудниках Заказчика;")
    add_bullet(doc, "бизнес-показатели, договоры, финансовая отчётность Заказчика;")
    add_bullet(doc, "сведения, помеченные грифом «конфиденциально», «коммерческая тайна», «персональные данные»;")
    add_bullet(doc, "сведения, обработка которых регулируется 152-ФЗ и Приложением № 4.")

    add_h2(doc, "2.2. Со стороны Исполнителя — Заказчику")
    add_bullet(doc, "методики и регламенты оказания Услуг, внутренние инструкции, runbooks;")
    add_bullet(doc, "разработанные Исполнителем кастомные Ansible-роли, Puppet-манифесты, скрипты автоматизации, правила мониторинга и SIEM;")
    add_bullet(doc, "архитектура мониторинга, SIEM, систем резервного копирования Исполнителя;")
    add_bullet(doc, "коммерческие условия (за исключением условий, указанных в Договоре и его Приложениях);")
    add_bullet(doc, "контакты и реквизиты партнёров, соисполнителей, поставщиков услуг;")
    add_bullet(doc, "переписка, отчёты, аналитические материалы Исполнителя.")

    # ------------------------------------------------------------------
    add_h1(doc, "3. Что не является конфиденциальной информацией")
    add_paragraph(doc, "Конфиденциальной не является информация, которая:")
    add_bullet(doc, "общедоступна на момент получения, не по вине Получающей Стороны;")
    add_bullet(doc, "правомерно получена Получающей Стороной от третьего лица, не связанного обязательством о неразглашении;")
    add_bullet(doc, "независимо разработана Получающей Стороной без использования конфиденциальной информации Раскрывающей Стороны (подтверждается письменными доказательствами);")
    add_bullet(doc, "раскрыта в силу обязательного требования закона или вступившего в законную силу судебного акта; в этом случае Получающая Сторона обязана уведомить Раскрывающую Сторону в течение 1 рабочего дня (если такое уведомление само не нарушает закон).")

    # ------------------------------------------------------------------
    add_h1(doc, "4. Обязательства Получающей Стороны")
    add_clause(doc, "4.1", "Использовать конфиденциальную информацию исключительно для целей исполнения Договора.")
    add_clause(doc, "4.2", "Не разглашать конфиденциальную информацию третьим лицам без письменного согласия Раскрывающей Стороны, за исключением соисполнителей и сотрудников Получающей Стороны, которым информация необходима для исполнения Договора. Передача соисполнителям возможна только при наличии у соисполнителя обязательства о неразглашении не ниже настоящего.")
    add_clause(doc, "4.3", "Принимать разумные технические и организационные меры для обеспечения сохранности конфиденциальной информации, не уступающие мерам, применяемым Получающей Стороной к собственной конфиденциальной информации.")
    add_clause(doc, "4.4", "Уведомить Раскрывающую Сторону о факте утечки или подозрении на утечку конфиденциальной информации в течение **24 (двадцати четырёх) часов**.")
    add_clause(doc, "4.5", "По окончании срока действия Договора либо по требованию Раскрывающей Стороны — в течение **30 (тридцати) календарных дней** уничтожить или вернуть полученную конфиденциальную информацию, за исключением сведений, которые Получающая Сторона обязана хранить в силу законодательства (например, финансовая отчётность — 5 лет в силу 402-ФЗ).")

    # ------------------------------------------------------------------
    add_h1(doc, "5. Особые обязательства Исполнителя")
    add_clause(
        doc, "5.1",
        "Исполнитель **не использует обезличенные сведения** о клиентах Заказчика, иных "
        "субъектах ПДн Заказчика и о коммерчески чувствительных данных Заказчика в "
        "маркетинговых материалах, кейсах, портфолио без письменного согласия Заказчика.",
    )
    add_clause(
        doc, "5.2",
        "Исполнитель **вправе** использовать **обезличенную информацию о факте оказания Услуг** "
        "(без указания наименования Заказчика, контактных лиц, специфики бизнеса, идентифицирующих "
        "признаков) в собственных маркетинговых материалах и портфолио. Использование "
        "идентифицирующих сведений — только с письменного согласия Заказчика.",
    )

    # ------------------------------------------------------------------
    add_h1(doc, "6. Особые обязательства Заказчика")
    add_clause(
        doc, "6.1",
        "Заказчик **не передаёт третьим лицам** методики, скрипты, плейбуки, правила Wazuh, "
        "конфигурации мониторинга, разработанные Исполнителем, без письменного согласия "
        "Исполнителя.",
    )
    add_clause(
        doc, "6.2",
        "Заказчик **не использует** материалы, разработанные Исполнителем, для оказания услуг "
        "третьим лицам.",
    )
    add_clause(
        doc, "6.3",
        "Заказчик **не публикует** сведения о коммерческих условиях Договора в открытых "
        "источниках, в том числе в социальных сетях, на тендерных площадках, в открытых рейтингах.",
    )

    # ------------------------------------------------------------------
    add_h1(doc, "7. Срок действия обязательств")
    add_paragraph(
        doc,
        "Обязательства Получающей Стороны по сохранению конфиденциальности действуют:",
    )
    add_bullet(doc, "в течение всего срока действия Договора;")
    add_bullet(doc, "в течение **3 (трёх) лет** после прекращения Договора по любому основанию;")
    add_bullet(doc, "в отношении сведений, составляющих коммерческую тайну (в смысле 98-ФЗ от 29.07.2004), — бессрочно, до момента отнесения этих сведений к общедоступной информации.")

    # ------------------------------------------------------------------
    add_h1(doc, "8. Ответственность")
    add_clause(
        doc, "8.1",
        "За нарушение обязательств по настоящему Соглашению виновная Сторона уплачивает другой "
        "Стороне **штраф в размере шестикратного ежемесячного вознаграждения** Исполнителя по "
        "Договору (с учётом действующего на момент нарушения Тарифа), за каждый случай "
        "нарушения. Помимо штрафа, потерпевшая Сторона вправе потребовать возмещения "
        "документально подтверждённых убытков.",
    )
    add_clause(
        doc, "8.2",
        "Штраф за нарушение обязательств по конфиденциальности **не подпадает под общий лимит "
        "совокупной ответственности Сторон**, установленный п. 8.1 основного Договора.",
    )
    add_clause(
        doc, "8.3",
        "Случай нарушения должен быть документально подтверждён потерпевшей Стороной "
        "(скриншоты публикаций, переписка, акт фиксации). При наличии подтверждения штраф "
        "уплачивается в течение **10 (десяти) рабочих дней** с момента направления требования.",
    )

    # ------------------------------------------------------------------
    add_h1(doc, "9. Применимое право")
    add_paragraph(
        doc,
        "К настоящему Соглашению применяется законодательство Российской Федерации, в том числе "
        "положения ст. 1465 ГК РФ (секрет производства), Федерального закона от 29.07.2004 "
        "№ 98-ФЗ «О коммерческой тайне», Федерального закона от 27.07.2006 № 152-ФЗ "
        "«О персональных данных».",
    )

    # ------------------------------------------------------------------
    add_h1(doc, "10. Подписи Сторон")
    add_signature_block(
        doc,
        [
            ("Исполнитель", ["__ФИО__, плательщик НПД", "ИНН: __________________"]),
            ("Заказчик", ["__Полное наименование__", "ИНН: __________________"]),
        ],
    )

    path = save(doc, "06_prilozhenie_5_nda.docx")
    print(f"OK: {path}")


if __name__ == "__main__":
    build()
